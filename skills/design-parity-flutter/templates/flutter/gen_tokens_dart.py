#!/usr/bin/env python3
"""Generates the app's theme constants from tokens.json, so the board and the app share one source.

    python3 gen_tokens_dart.py tokens.json lib/design_tokens.g.dart

Emits (Flutter):
  DesignPalette.light / .dark      every palette colour as a const Color
  DesignTokens.typeSizes / weights / radii / iconSizes / iconWeight(size)
  DesignTokens.<style>             each text style as a const TextStyle: fontSize, weight and `height = lh / size` with
                                   even leading, so a Text laid out in a box of height `lh` has the baseline the board
                                   computed from the same style
  DesignShadows.<name>(dark)       BoxShadow lists (blurRadius = the token's blur; the board's sigma is blur / 2)
Standard library only.
"""
import json
import re
import sys


def camel(key):
    parts = re.split(r'[-_ ]+', key)
    return parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:])


def color(hex_, opacity=1.0):
    h = hex_.lstrip('#')
    a = round(opacity * 255)
    return f'Color(0x{a:02X}{h.upper()})'


def main():
    src, dst = sys.argv[1], sys.argv[2]
    t = json.load(open(src, encoding='utf-8'))
    sc = t['scales']
    fam = t.get('fonts', {})
    o = ['// GENERATED by gen_tokens_dart.py from tokens.json. Do not edit; change tokens.json and regenerate.',
         "import 'package:flutter/painting.dart';", '']
    keys = list(t['palettes']['light'])
    o.append('class DesignPalette {')
    o.append('  const DesignPalette({' + ', '.join(f'required this.{camel(k)}' for k in keys if k != 'scrimOp') + ', required this.scrimOp});')
    for k in keys:
        o.append(f'  final {"double" if k == "scrimOp" else "Color"} {camel(k)};')
    for mode in ('light', 'dark'):
        vals = t['palettes'][mode]
        args = ', '.join(f'{camel(k)}: ' + (repr(float(v)) if k == 'scrimOp' else color(v)) for k, v in vals.items())
        o.append(f'  static const {mode} = DesignPalette({args});')
    o.append('}')
    o.append('')
    o.append('abstract final class DesignTokens {')
    o.append(f'  static const List<double> typeSizes = {[float(x) for x in sc["type_sizes"]]};')
    o.append(f'  static const List<int> weights = {list(sc["weights"])};')
    o.append(f'  static const List<double> radii = {[float(x) for x in sc["radii"]]};')
    o.append(f'  static const List<double> iconSizes = {[float(x) for x in sc["icon_sizes"]]};')
    rules = sc['icon_stroke_units']
    chain = ' : '.join([f'size <= {float(r["max"])!r} ? {round(r["units"] * 200)}' for r in rules[:-1]] + [str(round(rules[-1]['units'] * 200))])
    o.append('  /// Font weight (= stroke) of an icon drawn at `size`: the board\'s icon_stroke_units rule, units * 200.')
    o.append(f'  static int iconWeight(double size) => {chain};')
    o.append(f"  static const String sansFamily = '{fam.get('sans', 'Roboto')}';")
    o.append(f"  static const String monoFamily = '{fam.get('mono', 'monospace')}';")
    for name, s in t['text_styles'].items():
        family = 'monoFamily' if s.get('mono') else 'sansFamily'
        o.append(f'  static const TextStyle {camel(name)} = TextStyle(fontFamily: {family}, fontSize: {float(s["size"])!r}, '
                 f'fontWeight: FontWeight.w{s["weight"]}, height: {s["lh"] / s["size"]!r}, '
                 f'leadingDistribution: TextLeadingDistribution.even);')
    o.append('}')
    o.append('')
    o.append('abstract final class DesignShadows {')
    for name, modes in t.get('shadows', {}).items():
        for mode in ('light', 'dark'):
            s = modes[mode]
            o.append(f'  static const List<BoxShadow> {camel(name)}{"Dark" if mode == "dark" else ""} = '
                     f'[BoxShadow(color: {color(s["color"], s["opacity"])}, offset: Offset({float(s["dx"])!r}, {float(s["dy"])!r}), '
                     f'blurRadius: {float(s["blur"])!r})];')
    o.append('}')
    with open(dst, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(o) + '\n')
    print(f'wrote {dst}: {len(keys)} colours x 2, {len(t["text_styles"])} text styles, {len(t.get("shadows", {}))} shadows')


if __name__ == '__main__':
    main()
